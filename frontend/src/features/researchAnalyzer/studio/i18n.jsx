const LangContext = createContext(null);

export function StudioLangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('resref_analyzer_lang') === 'ar' ? 'ar' : 'en'; } catch { return 'en'; }
  });
  const value = useMemo(() => ({
    lang,
    isRTL: lang === 'ar',
    t: STRINGS[lang],
    setLang: (next) => {
      setLang(next);
      try { localStorage.setItem('resref_analyzer_lang', next); } catch { /* storage may be unavailable */ }
    },
  }), [lang]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useStudioLang() {
  return useContext(LangContext);
}
