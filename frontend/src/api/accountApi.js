import { get, post } from './apiClient';

export const AccountApi = {
  getConfig: () => get('/accounts/config/'),
  getMe: () => get('/accounts/me/'),
  register: payload => post('/accounts/register/', payload),
  confirmRegistration: token => post('/accounts/register/confirm/', { token }),
  resendConfirmation: email => post('/accounts/register/resend/', { email }),
  login: payload => post('/accounts/login/', payload),
  googleLogin: credential => post('/accounts/google/', { credential }),
  logout: () => post('/accounts/logout/', {}),
  getToolWorkspace: toolKey => get(`/accounts/tool-workspaces/${encodeURIComponent(toolKey)}/`),
  saveToolWorkspace: (toolKey, data) => post(`/accounts/tool-workspaces/${encodeURIComponent(toolKey)}/`, { data }),
  recordToolUsage: toolKey => post(`/accounts/tool-usage/${encodeURIComponent(toolKey)}/`, {}),
  updateProfile: payload => post('/accounts/profile/', payload),
  changePassword: payload => post('/accounts/password/', payload),
  requestEmailVerification: () => post('/accounts/email-verification/', {}),
  confirmEmailVerification: token => post('/accounts/email-verification/confirm/', { token }),
  createBillingCheckout: plan => post('/accounts/billing/checkout/', { plan }),
  openBillingPortal: () => post('/accounts/billing/portal/', {}),
  cancelSubscription: () => post('/accounts/billing/cancel/', {}),
  getNotifications: () => get('/accounts/notifications/'),
  markNotificationRead: id => post(`/accounts/notifications/${encodeURIComponent(id)}/read/`, {}),
  requestEmailChange: payload => post('/accounts/email/', payload),
  confirmEmailChange: token => post('/accounts/email/confirm/', { token }),
  exportAccount: () => get('/accounts/export/', { retry: false }),
  deleteAccount: payload => post('/accounts/delete/', payload),
  requestPasswordReset: email => post('/accounts/password-reset/', { email }),
  confirmPasswordReset: payload => post('/accounts/password-reset/confirm/', payload),
};
